#Data Types
#String
name = "Alice"
print(name)
#Integer
age = 30
print(age)
#Float
height = 5.5
print(height)
#Boolean
is_student = True
print(is_student)
#List
fruits = ["apple", "banana", "cherry"]
print(fruits)
#Tuple
coordinates = (10, 20)
print(coordinates)
#Dictionary
person = {"name": "Alice", "age": 30}
print(person)   
