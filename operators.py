# Arithmetic Operators
x = 15
y = 4

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y)
print(x ** y)
print(x // y)

# Comparison Operators
a = 10
b = 20

print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

# Logical Operators
p = True
q = False

print(p and q)
print(p or q)
print(not p)

# Assignment Operators
c = 5
c += 3
print(c)

# Bitwise Operators
m = 10
n = 4 
print(m & n) 
print(m | n) 
print(m ^ n) 
print(~m)    

# Shift Operators
print(m << 2)  # Left shift
print(m >> 2)  # Right shift

# Membership Operators
list1 = [1, 2, 3, 4, 5]
print(3 in list1)
print(6 not in list1)

# Identity Operators
x1 = 10
y1 = 10
print(x1 is y1)
z1 = [1, 2, 3]
print(z1 is not list1)